// Command gen builds names_gen.go and entities_gen.go from the C# sources of z3l.FastHtmlParser,
// so that the Go port uses exactly the same tag list and HTML5 entity table.
//
//	go run ./internal/gen <path to z3l.FastHtmlParser/src/z3l.FastHtmlParser>
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf16"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen <path to src/z3l.FastHtmlParser>")
		os.Exit(2)
	}
	src := os.Args[1]
	write("names_gen.go", tags(filepath.Join(src, "HtmlTag.cs")))
	write("entities_gen.go", entities(filepath.Join(src, "Core", "HtmlEntities.Table.cs")))
}

func write(name string, code []byte) {
	formatted, err := format.Source(code)
	check(err)
	check(os.WriteFile(name, formatted, 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

var special = map[string]string{"Comment": "!--", "Doctype": "!doctype", "XmlDeclaration": "?xml"}

func tags(path string) []byte {
	data, err := os.ReadFile(path)
	check(err)
	text := string(data)
	body := text[strings.Index(text, "public enum HtmlTag"):]
	body = body[strings.Index(body, "{")+1 : strings.LastIndex(body, "}")]

	var members []string
	for _, line := range strings.Split(body, "\n") {
		if i := strings.Index(line, "//"); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(strings.TrimSuffix(strings.TrimSpace(line), ","))
		if line != "" {
			members = append(members, line)
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from HtmlTag.cs; DO NOT EDIT.\n\npackage fasthtml\n\n")
	b.WriteString("// Known tag names: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap).\nconst (\n")
	for i, m := range members {
		if i == 0 {
			fmt.Fprintf(&b, "\tTag%s Tag = iota\n", m)
		} else {
			fmt.Fprintf(&b, "\tTag%s\n", m)
		}
	}
	b.WriteString("\ttagCount\n)\n\nvar tagNames = [tagCount]string{\n")
	for _, m := range members {
		name, ok := special[m]
		if !ok {
			name = strings.ToLower(m)
		}
		fmt.Fprintf(&b, "\t%q,\n", name)
	}
	b.WriteString("}\n")
	return b.Bytes()
}

var literal = regexp.MustCompile(`"((?:[^"\\]|\\.)*)"`)

// constant returns the concatenated string literals of `name = "..." + "...";`, escapes left as written.
func constant(text, name string) string {
	start := strings.Index(text, name+" =")
	end := start + strings.Index(text[start:], ";")
	var b strings.Builder
	for _, m := range literal.FindAllStringSubmatch(text[start:end], -1) {
		b.WriteString(m[1])
	}
	return b.String()
}

// utf16Units decodes C# escapes (\uXXXX, \0) into UTF-16 code units.
func utf16Units(s string) []uint16 {
	var units []uint16
	for i := 0; i < len(s); {
		switch {
		case strings.HasPrefix(s[i:], `\u`):
			v, err := strconv.ParseUint(s[i+2:i+6], 16, 16)
			check(err)
			units = append(units, uint16(v))
			i += 6
		case strings.HasPrefix(s[i:], `\0`):
			units = append(units, 0)
			i += 2
		default:
			units = append(units, uint16(s[i]))
			i++
		}
	}
	return units
}

func entities(path string) []byte {
	data, err := os.ReadFile(path)
	check(err)
	text := string(data)
	names := strings.Fields(constant(text, "private const string Names"))
	values := utf16Units(constant(text, "private const string Values"))
	if len(values) != 2*len(names) {
		check(fmt.Errorf("%d names, %d value units", len(names), len(values)))
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen from HtmlEntities.Table.cs; DO NOT EDIT.\n\npackage fasthtml\n\n")
	b.WriteString("// HTML5 named character references (without '&' and ';'); legacy ones are also recognized without ';'.\n")
	b.WriteString("var entityTable = map[string]entity{\n")
	maxName, maxLegacy := 0, 0
	for i, name := range names {
		legacy := strings.HasPrefix(name, "+")
		name = strings.TrimPrefix(name, "+")
		units := values[2*i : 2*i+2]
		if units[1] == 0 {
			units = units[:1]
		}
		value := string(utf16.Decode(units))
		fmt.Fprintf(&b, "\t%q: {%q, %v},\n", name, value, legacy)
		maxName = max(maxName, len(name))
		if legacy {
			maxLegacy = max(maxLegacy, len(name))
		}
	}
	fmt.Fprintf(&b, "}\n\nconst (\n\tentityMaxName = %d\n\tentityMaxLegacyName = %d\n)\n", maxName, maxLegacy)
	return b.Bytes()
}
